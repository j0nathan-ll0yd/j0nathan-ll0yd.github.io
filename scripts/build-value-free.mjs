#!/usr/bin/env node
/* The value-free pages, checked at build time and compiled into the Worker (atlas decision 0164
 * row 1; owner decision 2026-11-01, option B). `pnpm build` (scripts/build-site.mjs) runs it after
 * scripts/build-composer.mjs has built this build's composer, between the two `astro build` passes:
 *
 * 1. It asks this build's composer for the value-free pages (`composeValueFree`, the export the
 *    backend runner also calls): one per hiding focus value, one for the gate, one for an unreadable
 *    focus signal.
 * 2. It runs the Worker's own allowlist over every variant (src/lib/composed/artifact.ts
 *    `checkValueFreeSet`, which calls `checkFragments`) and fails the build on any refusal.
 * 3. It writes the admitted set, and the sha256 of its JSON text, into the generated module
 *    src/lib/composed/value-free.generated.ts (gitignored), which the second `astro build` compiles
 *    into the Worker (src/lib/composed/compiled-value-free.ts).
 *
 * The Worker does not read, parse or check these pages when it serves them. `--check`, after the
 * second `astro build`, runs the gate again on the exact values the module holds, proves the module
 * is what this script writes for this build's composer, and that exactly one Worker module holds it.
 *
 * Run with tsx: it imports the TypeScript check from src/. */
import {createHash} from 'node:crypto'
import {existsSync, readFileSync, writeFileSync} from 'node:fs'
import path from 'node:path'
import {fileURLToPath, pathToFileURL} from 'node:url'
import {checkValueFreeSet} from '../src/lib/composed/artifact.ts'
import {VALUE_FREE_VARIANTS} from '../src/lib/composed/value-free.ts'
import {bundlesNaming, isMainModule} from './lib/build-gates.mjs'
import {buildId} from './lib/build-id.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
export const VALUE_FREE_MODULE = path.join(ROOT, 'src/lib/composed/value-free.generated.ts')
const COMPOSER = path.join(ROOT, 'dist-composer', 'composer.mjs')

/** The set the Worker's allowlist admits for build `build`. Throws, and so fails the build, on any refusal. */
export function gatedValueFree(set, build) {
  const checked = checkValueFreeSet(set, build, VALUE_FREE_VARIANTS)
  if (!checked.ok) {
    throw new Error(`[build-value-free] the Worker's allowlist refuses the value-free pages (${checked.detail})`)
  }
  return checked.set
}

/** The sha256 of a set's JSON text: the bytes the gate checked, and the mark the Worker bundle carries. */
export function valueFreeSha256(set) {
  return createHash('sha256').update(JSON.stringify(set)).digest('hex')
}

/** The generated module's source for `set`, after the gate admitted it for build `build`. */
export function valueFreeModule(set, build) {
  const checked = gatedValueFree(set, build)
  return [
    "// GENERATED by scripts/build-value-free.mjs from this build's composer, after the Worker's own",
    '// allowlist admitted every variant (atlas decision 0164 row 1). Do not edit: every build rewrites',
    '// it, and git ignores it.',
    "import type {ValueFreeSet} from './artifact'",
    '',
    '/** The sha256 of the JSON text of VALUE_FREE_SET: the bytes the build checked. */',
    `export const VALUE_FREE_SHA256 = ${JSON.stringify(valueFreeSha256(checked))}`,
    '',
    "/** The value-free pages, admitted by the Worker's own allowlist at build time. */",
    `export const VALUE_FREE_SET: ValueFreeSet = ${JSON.stringify(checked)}`,
    ''
  ].join('\n')
}

/** The value-free pages this build's composer composes. Throws when the composer is another build's. */
export async function composedValueFree(build = buildId()) {
  if (!existsSync(COMPOSER)) {
    throw new Error('[build-value-free] dist-composer/composer.mjs is missing: scripts/build-composer.mjs runs first')
  }
  const composer = await import(pathToFileURL(COMPOSER).href)
  if (composer.COMPOSER_BUILD !== build) {
    throw new Error(`[build-value-free] the composer names build ${composer.COMPOSER_BUILD}, not ${build}`)
  }
  return composer.composeValueFree()
}

/**
 * The check after the second `astro build`: the module that build compiled in (`moduleText`, and
 * `compiled`, its exported values) must be `source`, what this script writes for this build's composer;
 * the gate must admit the exact values it holds, whose sha256 must be the one it carries; and exactly
 * one module of the Worker bundle in `serverDirectory` must hold that sha256. Throws on any failure;
 * returns the module that holds it.
 */
export function checkCompiledValueFree({source, moduleText, compiled, build, serverDirectory}) {
  if (moduleText !== source) {
    throw new Error("[build-value-free] the compiled value-free pages are not the checked pages of this build's composer")
  }
  const admitted = gatedValueFree(compiled.VALUE_FREE_SET, build)
  if (valueFreeSha256(compiled.VALUE_FREE_SET) !== compiled.VALUE_FREE_SHA256 || valueFreeSha256(admitted) !== compiled.VALUE_FREE_SHA256) {
    throw new Error('[build-value-free] the compiled value-free pages do not match the sha256 the build checked')
  }
  const holders = bundlesNaming(compiled.VALUE_FREE_SHA256, serverDirectory)
  if (holders.length !== 1) {
    throw new Error(`[build-value-free] ${holders.length} Worker modules hold the value-free pages, not 1`)
  }
  return holders[0]
}

if (isMainModule(import.meta.url)) {
  const build = buildId()
  const source = valueFreeModule(await composedValueFree(build), build)
  if (process.argv.includes('--check')) {
    if (!existsSync(VALUE_FREE_MODULE)) {
      throw new Error('[build-value-free] src/lib/composed/value-free.generated.ts is missing: the second astro build compiled no value-free pages')
    }
    const compiled = await import(pathToFileURL(VALUE_FREE_MODULE).href)
    const holder = checkCompiledValueFree({source, moduleText: readFileSync(VALUE_FREE_MODULE, 'utf8'), compiled, build})
    console.log(`[build-value-free] OK: dist/server/${holder} holds the checked value-free pages (sha256 ${compiled.VALUE_FREE_SHA256.slice(0, 12)})`)
  } else {
    writeFileSync(VALUE_FREE_MODULE, source)
    console.log(
      `[build-value-free] wrote ${path.relative(ROOT, VALUE_FREE_MODULE)} (${source.length} bytes): ${VALUE_FREE_VARIANTS.length} variants admitted`
    )
  }
}
