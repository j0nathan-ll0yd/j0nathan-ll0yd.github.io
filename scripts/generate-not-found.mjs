#!/usr/bin/env node
// scripts/generate-not-found.mjs -- writes src/lib/edge/not-found-markdown.mjs, the markdown 404
// body src/lib/edge/middleware.ts answers with (atlas decision 0158).
//
// WHY A GENERATED MODULE. The middleware runs on every request, so it imports nothing it could
// fail on at load (the rule src/lib/edge/agent-paths.mjs states). Building the body from
// @j0nathan-ll0yd/copy inside the middleware meant a missing copy key stopped the Worker from
// starting. Here the same missing key fails `pnpm build` at prebuild, with its name in the error,
// and the middleware imports one constant string.
//
// `--check` exits 1 when the committed module differs from what this script renders, so a copy
// bump that changes the 404 cannot ship a stale body. tests/unit/not-found-markdown.test.ts
// runs the same comparison.

import {readFileSync, writeFileSync} from 'node:fs'
import {dirname, join} from 'node:path'
import {fileURLToPath} from 'node:url'
import llm from '@j0nathan-ll0yd/copy/llm.flat.json' with {type: 'json'}
import {LLM_CONTENT_PATHS, SITE_URL} from '@j0nathan-ll0yd/portal-contract/constants'
import {AGENT_PATHS} from '../src/lib/edge/agent-paths.mjs'
import {LLMS_TXT_PATH} from '../src/lib/edge/llms-artifacts.ts'
import {SITEMAP_INDEX_PATH} from '../src/lib/edge/site-paths.ts'

export const OUTPUT_PATH = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'edge', 'not-found-markdown.mjs')

/** The copy key each 404 link reads, and the contract path its URL is built from. */
const LINKS = [
  ['linkLlmsTxt', LLMS_TXT_PATH],
  ['linkIndexMd', LLM_CONTENT_PATHS.indexMarkdown],
  ['linkSitemap', SITEMAP_INDEX_PATH],
  ['linkDevelopers', AGENT_PATHS.developers]
]

/** The is-agentic agent-friendly-404 check needs at least this much explanatory text. */
const MIN_BODY_CHARS = 20

function fail(message) {
  throw new Error(`[generate-not-found] ${message}`)
}

/**
 * The markdown 404 body. Throws, naming the key, when copy lacks a string or a link's own
 * `{siteUrl}` template names a different URL from the contract path.
 */
export function renderNotFoundMarkdown(copy = llm) {
  const notFound = copy?.notFound
  if (!notFound || typeof notFound.heading !== 'string' || typeof notFound.body !== 'string') {
    fail('@j0nathan-ll0yd/copy has no llm.notFound.heading / llm.notFound.body')
  }
  if (notFound.body.trim().length < MIN_BODY_CHARS) {
    fail(`llm.notFound.body is shorter than ${MIN_BODY_CHARS} characters`)
  }
  const lines = LINKS.map(([key, path]) => {
    const link = notFound[key]
    if (!link || typeof link.label !== 'string' || typeof link.notes !== 'string' || typeof link.url !== 'string') {
      fail(`@j0nathan-ll0yd/copy has no llm.notFound.${key} {label, notes, url}`)
    }
    const url = `${SITE_URL}${path}`
    if (link.url.replaceAll('{siteUrl}', SITE_URL) !== url) {
      fail(`llm.notFound.${key}.url (${link.url}) does not name the contract path ${url}`)
    }
    return `- [${link.label}](${url}): ${link.notes}`
  })
  return [`# ${notFound.heading}`, '', notFound.body, '', ...lines, ''].join('\n')
}

/** The module source: one exported constant, no imports. */
export function renderNotFoundModule(copy = llm) {
  return [
    '// GENERATED by scripts/generate-not-found.mjs from @j0nathan-ll0yd/copy (llm.notFound) and the',
    '// contract paths. Do not edit by hand: run `pnpm run generate:not-found`. Dependency-free on',
    '// purpose: src/lib/edge/middleware.ts imports it on every request.',
    `export const NOT_FOUND_MARKDOWN = ${JSON.stringify(renderNotFoundMarkdown(copy))}`,
    ''
  ].join('\n')
}

function main() {
  const rendered = renderNotFoundModule()
  if (process.argv.includes('--check')) {
    const committed = readFileSync(OUTPUT_PATH, 'utf8')
    if (committed !== rendered) {
      console.error(`[generate-not-found] ${OUTPUT_PATH} is stale; run \`pnpm run generate:not-found\``)
      process.exit(1)
    }
    console.log('[generate-not-found] OK: the committed markdown 404 matches the copy')
    return
  }
  writeFileSync(OUTPUT_PATH, rendered)
  console.log(`[generate-not-found] wrote ${OUTPUT_PATH}`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main()
}
